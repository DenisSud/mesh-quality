def _legacy_cache(cache_dir: Path, name: str) -> Path:
    """Locate a legacy ``.npz`` cache: live ``cache/`` first, then the archive."""
    for base in (cache_dir, cache_dir / LEGACY_CACHE_DIR):
        if (base / name).exists():
            return base / name
    raise SystemExit(f"{name} not found in {cache_dir} or {cache_dir / LEGACY_CACHE_DIR}")

